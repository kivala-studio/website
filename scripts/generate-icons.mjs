// Builds src/ui/icons/icon-pack.ts from the iOS outline masters (24-unit grid, 2-unit round strokes).
//
//   node scripts/generate-icons.mjs
//
// design/icon-pack/masters.json is an unchanged copy of iOS Tools/IconPack/masters.json.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const masters = JSON.parse(await readFile(path.join(ROOT, "design/icon-pack/masters.json"), "utf8"));

const ALLOWED = /^(?:<(?:path|circle|rect|line|polyline|ellipse)(?:\s+[a-z-]+="[^"<>]*")*\s*\/>)+$/;
const entries = masters.map(({ name, label, body }) => {
  if (!/^[a-z]+(?:-[a-z]+)*$/.test(name)) throw new Error(`Unexpected icon name: ${name}`);
  if (!ALLOWED.test(body)) throw new Error(`Unexpected markup in ${name}`);
  return `  ${JSON.stringify(name)}: { label: ${JSON.stringify(label)}, body: ${JSON.stringify(body)} },`;
});

const source = `// Generated by scripts/generate-icons.mjs from design/icon-pack/masters.json. Do not edit.
export const ICON_PACK = {
${entries.join("\n")}
} as const;

export type IconName = keyof typeof ICON_PACK;
`;
await writeFile(path.join(ROOT, "src/ui/icons/icon-pack.ts"), source);
console.log(`Generated ${masters.length} icons.`);
